-- =========================================
-- ECOVEL - JOURNEY LOCATIONS
-- =========================================

create table if not exists public.journey_locations (
    id bigint generated by default as identity primary key,

    journey_id bigint not null
        references public.journeys(id)
        on delete cascade,

    location_id bigint not null
        references public.locations(id)
        on delete cascade,

    stop_order integer not null
        check (stop_order > 0),

    created_at timestamptz not null default now(),

    unique (journey_id, location_id),
    unique (journey_id, stop_order)
);


-- =========================================
-- ROW LEVEL SECURITY
-- =========================================

alter table public.journey_locations
enable row level security;


drop policy if exists
"Journey locations are public"
on public.journey_locations;


create policy "Journey locations are public"
on public.journey_locations
for select
to anon, authenticated
using (true);


-- =========================================
-- SAMPLE DATA
-- =========================================

insert into public.journey_locations (
    journey_id,
    location_id,
    stop_order
)
values
    (1, 1, 1),
    (1, 2, 2),
    (1, 3, 3)
on conflict (journey_id, location_id)
do update set
