-- =========================================
-- ECOVEL - USER JOURNEYS
-- =========================================

create table if not exists public.user_journeys (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id)
        on delete cascade,

    journey_id bigint not null
        references public.journeys(id)
        on delete cascade,

    status text not null default 'joined'
        check (
            status in (
                'joined',
                'completed'
            )
        ),

    joined_at timestamptz not null default now(),

    completed_at timestamptz,

    unique (user_id, journey_id)
);


-- =========================================
-- ROW LEVEL SECURITY
-- =========================================

alter table public.user_journeys
enable row level security;


drop policy if exists
"Users can view own journeys"
on public.user_journeys;


drop policy if exists
"Users can create own journeys"
on public.user_journeys;


drop policy if exists
"Users can update own journeys"
on public.user_journeys;


create policy "Users can view own journeys"
on public.user_journeys
for select
to authenticated
using (
    auth.uid() = user_id
);


create policy "Users can create own journeys"
on public.user_journeys
for insert
to authenticated
with check (
    auth.uid() = user_id
);


create policy "Users can update own journeys"
on public.user_journeys
for update
to authenticated
using (
    auth.uid() = user_id
)
with check (
    auth.uid() = user_id
);