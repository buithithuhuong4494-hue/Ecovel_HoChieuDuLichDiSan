-- =========================================
-- ECOVEL - POINT SYSTEM
-- =========================================

-- Quy tắc:
-- Check-in hợp lệ:          +10 điểm
-- Hoàn thành hành trình:    +50 điểm
-- Mở khóa huy hiệu:         +20 điểm
--
-- Bảng point_events dùng để tránh cộng điểm trùng.


-- =========================================
-- 1. POINT EVENTS
-- =========================================

create table if not exists public.point_events (
    id bigint generated by default as identity primary key,

    user_id uuid not null
        references public.profiles(id)
        on delete cascade,

    event_type text not null
        check (
            event_type in (
                'checkin',
                'journey',
                'badge'
            )
        ),

    reference_id bigint not null,

    points integer not null
        check (points > 0),

    created_at timestamptz
        not null default now(),

    unique (
        user_id,
        event_type,
        reference_id
    )
);


-- =========================================
-- 2. RLS
-- =========================================

alter table public.point_events
enable row level security;


drop policy if exists
"Users can view own point events"
on public.point_events;


create policy
"Users can view own point events"
on public.point_events
for select
to authenticated
using (
    auth.uid() = user_id
);


-- Không tạo INSERT / UPDATE policy.
-- Điểm chỉ được cộng bởi function phía database.


-- =========================================
-- 3. HELPER FUNCTION
-- CỘNG ĐIỂM MỘT LẦN DUY NHẤT
-- =========================================

create or replace function public.award_points(
    p_user_id uuid,
    p_event_type text,
    p_reference_id bigint,
    p_points integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
    inserted_id bigint;
begin

    insert into public.point_events (
        user_id,
        event_type,
        reference_id,
        points
    )
    values (
        p_user_id,
        p_event_type,
        p_reference_id,
        p_points
    )
    on conflict (
        user_id,
        event_type,
        reference_id
    )
    do nothing
    returning id
    into inserted_id;


    -- Nếu event đã tồn tại thì không cộng lại.
    if inserted_id is null then
        return false;
    end if;


    update public.profiles
    set
        total_points =
            total_points + p_points,

        updated_at = now()
    where id = p_user_id;


    return true;
end;
$$;


-- =========================================
-- 4. CHECK-IN POINTS
-- +10 ĐIỂM
-- =========================================

create or replace function public.handle_checkin_points()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

    if new.status = 'verified' then

        perform public.award_points(
            new.user_id,
            'checkin',
            new.id,
            10
        );

    end if;


    return new;
end;
$$;


drop trigger if exists
trigger_checkin_points
on public.check_ins;


create trigger trigger_checkin_points
after insert
on public.check_ins
for each row
execute function
public.handle_checkin_points();


-- =========================================
-- 5. AUTO COMPLETE JOURNEYS
-- =========================================

create or replace function public.check_completed_journeys()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare

    journey_record record;

    total_stops integer;

    completed_stops integer;

begin

    if new.status <> 'verified' then
        return new;
    end if;


    /*
      Một location có thể nằm trong
      nhiều hành trình.

      Sau khi check-in, kiểm tra tất cả
      hành trình có location đó.
    */

    for journey_record in

        select distinct
            jl.journey_id

        from public.journey_locations jl

        where
            jl.location_id =
                new.location_id

    loop

        -- Tổng số điểm dừng
        select count(*)
        into total_stops

        from public.journey_locations jl

        where
            jl.journey_id =
                journey_record.journey_id;


        -- Số điểm user đã check-in
        select count(distinct jl.location_id)
        into completed_stops

        from public.journey_locations jl

        join public.check_ins ci
            on ci.location_id =
                jl.location_id

        where
            jl.journey_id =
                journey_record.journey_id

            and ci.user_id =
                new.user_id

            and ci.status =
                'verified';


        -- Hoàn thành toàn bộ điểm
        if
            total_stops > 0
            and completed_stops >= total_stops
        then

            insert into public.user_journeys (
                user_id,
                journey_id,
                status,
                completed_at
            )
            values (
                new.user_id,
                journey_record.journey_id,
                'completed',
                now()
            )

            on conflict (
                user_id,
                journey_id
            )

            do update
            set
                status =
                    'completed',

                completed_at =
                    coalesce(
                        public.user_journeys.completed_at,
                        now()
                    );


            -- +50 điểm
            perform public.award_points(
                new.user_id,
                'journey',
                journey_record.journey_id,
                50
            );

        end if;

    end loop;


    return new;
end;
$$;


drop trigger if exists
trigger_check_completed_journeys
on public.check_ins;


create trigger trigger_check_completed_journeys
after insert
on public.check_ins
for each row
execute function
public.check_completed_journeys();


